-- Production PostgreSQL schema.
CREATE TABLE IF NOT EXISTS parametros_cargo (
  cargo         VARCHAR(150) PRIMARY KEY,
  unidad        VARCHAR(80),
  std_directa   INT    NOT NULL,
  std_indirecta INT    NOT NULL,
  t40_dir DOUBLE PRECISION, t40_ind DOUBLE PRECISION, t40_nas DOUBLE PRECISION,   -- jornada >= 40 h
  t22_dir DOUBLE PRECISION, t22_ind DOUBLE PRECISION, t22_nas DOUBLE PRECISION,   -- entre 22 y 40 h
  t0_dir  DOUBLE PRECISION, t0_ind  DOUBLE PRECISION, t0_nas  DOUBLE PRECISION    -- menos de 22 h
);
CREATE TABLE IF NOT EXISTS factor_grupal (
  cod_esp VARCHAR(10) PRIMARY KEY, pct_grupal DOUBLE PRECISION, pacientes_san_con DOUBLE PRECISION, pacientes_otros DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS calendario_mes (mes INT PRIMARY KEY, semanas_habiles DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS calendario_it  (it INT, mes INT, semanas_habiles DOUBLE PRECISION NOT NULL, PRIMARY KEY (it, mes));
CREATE TABLE IF NOT EXISTS parametros_generales (clave VARCHAR(50) PRIMARY KEY, valor DOUBLE PRECISION NOT NULL, descripcion VARCHAR(200));
CREATE TABLE IF NOT EXISTS catalogo_asignaciones (
  nombre VARCHAR(120) PRIMARY KEY, horas_semanales DOUBLE PRECISION NOT NULL, requiere_autorizacion BOOLEAN DEFAULT FALSE
);

-- ===== Datos de entrada (los llena el bot / el simulador) =====
CREATE TABLE IF NOT EXISTS contratos (
  persona_id INT NOT NULL, it INT NOT NULL, periodo DATE NOT NULL,
  instituto VARCHAR(30), ciudad VARCHAR(60), sub_area VARCHAR(100), cod_esp VARCHAR(10),
  tipo_contrato VARCHAR(40), tipo_trabajador VARCHAR(40), fecha_termino DATE,
  horas_semanales DOUBLE PRECISION NOT NULL, cargo VARCHAR(150) NOT NULL, reg_sic VARCHAR(20),
  archivo_origen VARCHAR(200), vigente BOOLEAN DEFAULT TRUE,
  PRIMARY KEY (persona_id, it, periodo)
);
CREATE TABLE IF NOT EXISTS cambios_detectados (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id INT NOT NULL, it INT NOT NULL,
  tipo VARCHAR(20) NOT NULL,          -- ALTA, BAJA, JORNADA, CARGO, CONTRATO, VIGENCIA, PERIODO_NUEVO
  detalle VARCHAR(300),
  periodo_desde DATE,                 -- fecha desde la que rige el cambio
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
  archivo VARCHAR(200),
  fecha_deteccion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  fecha_aplicacion TIMESTAMP
);
CREATE TABLE IF NOT EXISTS errores_carga (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, archivo VARCHAR(200), fila INT, persona_id INT,
  campo VARCHAR(60), mensaje VARCHAR(300), fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS log_ejecucion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, proceso VARCHAR(80), archivo VARCHAR(200), resultado VARCHAR(20),
  detalle VARCHAR(500), filas_leidas INT, filas_validas INT, errores INT, cambios INT,
  fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS asignaciones_persona (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, persona_id INT NOT NULL, nombre VARCHAR(120) NOT NULL,
  horas_semanales DOUBLE PRECISION NOT NULL, estado VARCHAR(30) NOT NULL,   -- APROBADA | PENDIENTE_AUTORIZACION
  solicitado_por VARCHAR(80), justificacion VARCHAR(300), fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ===== Resultado del calculo =====
CREATE TABLE IF NOT EXISTS resultado_planificacion (
  persona_id INT NOT NULL, it INT NOT NULL, periodo DATE NOT NULL,
  instituto VARCHAR(30), sub_area VARCHAR(100), cod_esp VARCHAR(10), cargo VARCHAR(150),
  horas_semanales DOUBLE PRECISION, tramo VARCHAR(12), horas_nas_sem DOUBLE PRECISION, horas_disp_sem DOUBLE PRECISION,
  horas_disp_directa_sem DOUBLE PRECISION, atenc_directa_sem DOUBLE PRECISION, atenc_total_sem DOUBLE PRECISION, semanas_mes DOUBLE PRECISION,
  plan_directa INT, plan_indirecta INT, plan_total INT, meta_gestion INT, foja DOUBLE PRECISION,
  calculado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (persona_id, it, periodo)
);
